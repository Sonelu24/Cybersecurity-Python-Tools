def parse_php_version(text: str) -> tuple[int, int, int] | None:
    """Extracts a (major, minor, patch) PHP version tuple from a header or config string."""
    m = re.search(r"\b(?:PHP[/\s:v-]*|php:)(\d+)\.(\d+)\.(\d+)\b", text, re.IGNORECASE)
    if m:
        return int(m.group(1)), int(m.group(2)), int(m.group(3))
    return None


def fetch_passive_headers(url: str, timeout: float = 6.0) -> dict[str, str]:
    """Performs a safe, passive HTTP HEAD/GET request to collect response headers."""
    target_url = url if "://" in url else f"https://{url}"
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    req = urllib.request.Request(
        target_url,
        method="HEAD",
        headers={"User-Agent": "PHP2Shell-Exposure-Auditor/2.0 (Passive Security Audit)"},
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as resp:
            return {k: v for k, v in resp.headers.items()}
    except Exception:
        req.method = "GET"
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as resp:
            return {k: v for k, v in resp.headers.items()}


def parse_php_ini(ini_text: str) -> dict[str, str]:
    """Parses active key = value directives from a php.ini file (ignoring comments)."""
    directives: dict[str, str] = {}
    for raw_line in ini_text.splitlines():
        line = raw_line.split(";", 1)[0].strip()
        if not line or line.startswith("[") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        directives[k.strip().lower()] = v.strip()
    return directives


def audit_composer_data(composer_data: dict) -> list[dict]:
    """Checks composer.json require.php and config.platform.php for EOL or unpatched pins."""
    issues = []
    req_php = str(composer_data.get("require", {}).get("php", ""))
    plat_php = str(composer_data.get("config", {}).get("platform", {}).get("php", ""))

    if re.search(r"(?:^|\D)(?:5\.|7\.|8\.[01])\b", f"{req_php} {plat_php}"):
        issues.append({
            "severity": "HIGH",
            "title": f"Composer Allows EOL Unpatched PHP Branch ('{req_php or plat_php}')",
            "detail": "composer.json permits PHP <= 8.1, which received no upstream PHP2Shell patch.",
            "remediation": "Update composer.json 'require.php' / 'config.platform.php' to '>=8.3.36 || >=8.4.27'.",
        })

    if plat_php:
        m = re.match(r"^(\d+)\.(\d+)\.(\d+)$", plat_php.strip())
        if m:
            ver_t = (int(m.group(1)), int(m.group(2)), int(m.group(3)))
            floor = PATCHED_FLOORS.get((ver_t[0], ver_t[1]))
            if floor and ver_t < floor:
                floor_str = ".".join(map(str, floor))
                issues.append({
                    "severity": "HIGH",
                    "title": f"Composer Platform Locked Below Patch Floor (platform.php = {plat_php} < {floor_str})",
                    "detail": "CI/CD builds pinned via config.platform.php target an unpatched PHP2Shell runtime.",
                    "remediation": f"Bump composer.json config.platform.php to '{floor_str}'.",
                })
    return issues


def evaluate_exposure(
    target_label: str,
    headers: dict[str, str],
    ini_directives: dict[str, str],
    dockerfile_text: str = "",
    composer_data: dict | None = None,
) -> dict:
    """Audits PHP version, SAPI architecture, php.ini, and composer.json for PHP2Shell exposure."""
    findings = []
    remediations = []
    risk_score = 0

    norm_headers = {k.lower(): v for k, v in headers.items()}
    server_hdr = norm_headers.get("server", "")
    powered_by = norm_headers.get("x-powered-by", "")
    combined_banner = f"{server_hdr} {powered_by} {dockerfile_text}"

    version_tuple = parse_php_version(combined_banner)
    ver_str = ".".join(map(str, version_tuple)) if version_tuple else "Hidden / Undisclosed"

    # Detect SAPI architecture
    if ("apache" in server_hdr.lower() and "php/" in server_hdr.lower()) or "libapache2-mod-php" in dockerfile_text.lower():
        sapi_mode = "Apache mod_php (In-Process Worker — HIGHEST RISK)"
        is_mod_php = True
    elif "fpm" in combined_banner.lower():
        sapi_mode = "PHP-FPM (FastCGI Worker Pool)"
        is_mod_php = False
    else:
        sapi_mode = "Undisclosed SAPI"
        is_mod_php = False

    # 1. PHP Version vs October 2026 PHP2Shell Patch Floor
    if version_tuple:
        branch = (version_tuple[0], version_tuple[1])
        if branch in PATCHED_FLOORS:
            patched_ver = PATCHED_FLOORS[branch]
            patched_str = ".".join(map(str, patched_ver))
            if version_tuple < patched_ver:
                findings.append({
                    "severity": "CRITICAL",
                    "title": f"Vulnerable PHP Runtime Detected (PHP {ver_str} < {patched_str})",
                    "detail": (
                        "Exposed to PHP2Shell pre-auth RCE (CVE-2026-109618 OOM longjmp corruption & "
                        "CVE-2026-109619 worker Use-After-Free, CVSS 9.2)."
                    ),
                })
                remediations.append(f"Upgrade PHP {ver_str} -> {patched_str}+ immediately.")
                risk_score += 55
        elif version_tuple < (8, 2, 0):
            findings.append({
                "severity": "CRITICAL",
                "title": f"End-of-Life Unpatched PHP Branch (PHP {ver_str})",
                "detail": "PHP <= 8.1 / 7.x / 5.x received NO official upstream patches for CVE-2026-109618 / CVE-2026-109619.",
            })
            remediations.append("Migrate off EOL PHP branch to PHP 8.3.36+, 8.4.27+, or 8.5.12+.")
            risk_score += 60

    # 2. High-Risk Apache mod_php SAPI Check
    if is_mod_php:
        findings.append({
            "severity": "HIGH",
            "title": "High-Risk Apache 'mod_php' SAPI Architecture",
            "detail": (
                "PHP runs inside persistent Apache worker processes; pre-auth request parsing bugs trigger "
                "before application logic or WAF rules execute."
            ),
        })
        remediations.append("Migrate from Apache mod_php to isolated PHP-FPM workers with MaxRequestsPerChild limits.")
        risk_score += 20

    # 3. php.ini Hardening Checks
    if ini_directives:
        up_prog = ini_directives.get("session.upload_progress.enabled", "on").lower()
        if up_prog in ("on", "1", "true"):
            findings.append({
                "severity": "HIGH",
                "title": "Upload Progress State Tracking Enabled (session.upload_progress.enabled = On)",
                "detail": "Exposes the CVE-2026-109619 / CVE-2026-115560 persistent worker state Use-After-Free vector.",
            })
            remediations.append("Set 'session.upload_progress.enabled = Off' in php.ini (or use --write-hardened-ini).")
            risk_score += 15

        backtraces = ini_directives.get("zend.fatal_error_backtraces", "off").lower()
        if backtraces in ("on", "1", "true"):
            findings.append({
                "severity": "MEDIUM",
                "title": "Fatal Error Backtraces Enabled (zend.fatal_error_backtraces = On)",
                "detail": "Increases stale pointer retention across fatal OOM/shutdown errors in persistent workers.",
            })
            remediations.append("Set 'zend.fatal_error_backtraces = Off' in production php.ini.")
            risk_score += 10

        disabled_fns = ini_directives.get("disable_functions", "")
        if not disabled_fns:
            findings.append({
                "severity": "MEDIUM",
                "title": "Dangerous OS Execution Functions Enabled (disable_functions is empty)",
                "detail": "Allows post-exploitation web shells to invoke system(), exec(), passthru(), and shell_exec().",
            })
            remediations.append("Set 'disable_functions = exec,passthru,shell_exec,system,proc_open,popen' in php.ini.")
            risk_score += 10

    # 4. composer.json Platform & Version Constraints
    if composer_data:
        for issue in audit_composer_data(composer_data):
            findings.append({
                "severity": issue["severity"],
                "title": issue["title"],
                "detail": issue["detail"],
            })
            if issue["remediation"] not in remediations:
                remediations.append(issue["remediation"])
            risk_score += 15

    # 5. Version Banner Leak Check
    if powered_by or "php/" in server_hdr.lower() or ini_directives.get("expose_php", "").lower() in ("on", "1"):
        findings.append({
            "severity": "LOW",
            "title": f"PHP Version Banner Disclosed ('{powered_by or server_hdr}')",
            "detail": "Allows opportunistic scanners to fingerprint exact unpatched PHP versions passively.",
        })
        remediations.append("Set 'expose_php = Off' in php.ini and 'ServerTokens Prod' in Apache.")
        risk_score += 5

    risk_score = min(100, risk_score)
    if risk_score >= 75:
        grade = "F (CRITICAL EXPOSURE)"
    elif risk_score >= 50:
        grade = "D (HIGH EXPOSURE)"
    elif risk_score >= 25:
        grade = "C (MODERATE RISK)"
    elif risk_score >= 10:
        grade = "B (MINOR HARDENING NEEDED)"
    else:
        grade = "A (PATCHED & HARDENED)"

    return {
        "target": target_label,
        "detected_php_version": ver_str,
        "sapi_architecture": sapi_mode,
        "risk_score": risk_score,
        "grade": grade,
        "findings": findings,
        "remediations": remediations,
    }


def run_batch_scan(targets_file: Path) -> list[dict]:
    """Concurrently audits a list of target URLs from a file."""
    urls = [
        line.strip()
        for line in targets_file.read_text(encoding="utf-8", errors="ignore").splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    results = []

    def _worker(u: str) -> dict:
        try:
            hdrs = fetch_passive_headers(u)
            return evaluate_exposure(u, hdrs, {})
        except Exception as exc:
            return {
                "target": u,
                "detected_php_version": "Unreachable",
                "sapi_architecture": f"Error: {exc}",
                "risk_score": 0,
                "grade": "ERROR",
                "findings": [],
                "remediations": [],
            }

    with ThreadPoolExecutor(max_workers=8) as pool:
        future_map = {pool.submit(_worker, u): u for u in urls}
        for fut in as_completed(future_map):
            results.append(fut.result())

    print(f"[*] Batch Audited {len(results)} Target(s) from {targets_file.name}")
    print("=" * 76)
    print(f"  {'TARGET':<30} {'PHP VERSION':<16} {'SCORE':<8} {'GRADE'}")
    print("  " + "-" * 72)
    for r in sorted(results, key=lambda x: x["risk_score"], reverse=True):
        print(f"  {r['target'][:29]:<30} {r['detected_php_version']:<16} {r['risk_score']:>3}/100  {r['grade']}")
    print("=" * 76)
    return results


def export_report(data: dict | list, output_path: Path) -> None:
    """Exports single or batch assessment results to JSON or CSV."""
    if output_path.suffix.lower() == ".csv":
        rows = data if isinstance(data, list) else [data]
        with output_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(
                f,
                fieldnames=["target", "detected_php_version", "sapi_architecture", "risk_score", "grade"],
                extrasaction="ignore",
            )
            writer.writeheader()
            writer.writerows(rows)
    else:
        output_path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"[+] Exported assessment report to {output_path}")


def print_report(report: dict) -> None:
    """Prints a compact, single-screen PHP2Shell Exposure & Config Audit report."""
    print(f"[*] Audit Target     : {report['target']}")
    print(f"[*] Detected Runtime : PHP {report['detected_php_version']}  |  SAPI: {report['sapi_architecture']}")
    print("[*] Patch Floors     : 8.5.12 | 8.4.27 | 8.3.36 | 8.2.35  (CVE-2026-109618 / CVE-2026-109619)")
    print("=" * 76)

    print(f"\n[🚨 Security Exposure Findings ({len(report['findings'])})]")
    if not report["findings"]:
        print("  ✅ Target meets October 2026 PHP2Shell patch floors and hardening baselines.")
    else:
        for f in report["findings"]:
            sev = f"[{f['severity']}]"
            print(f"  • {sev:<10} {f['title']}")
            print(f"               └─ {f['detail']}")

    if report["remediations"]:
        print(f"\n[🛠️  Prioritized Remediation Checklist ({len(report['remediations'])})]")
        for idx, rem in enumerate(report["remediations"], 1):
            print(f"  {idx}. {rem}")

    print("\n" + "=" * 76)
    print(f"[!] EXPOSURE GRADE : {report['grade']}  (Risk Score: {report['risk_score']}/100)")
    print("=" * 76)


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    parser = argparse.ArgumentParser(
        description="Passively audit HTTP endpoints, php.ini, Dockerfiles, and composer.json for PHP2Shell exposure."
    )
    parser.add_argument("target", nargs="?", help="Target URL (https://example.com) to passively inspect headers")
    parser.add_argument("-i", "--input-list", help="Path to file of target URLs for concurrent batch auditing")
    parser.add_argument("--php-ini", help="Path to a local php.ini file to audit")
    parser.add_argument("--dockerfile", help="Path to a local Dockerfile to audit PHP base image & SAPI packages")
    parser.add_argument("--composer", help="Path to a local composer.json file to audit PHP version pins")
    parser.add_argument(
        "--write-hardened-ini",
        metavar="FILE",
        help="Generate a drop-in 99-php2shell-hardening.ini mitigation file",
    )
    parser.add_argument("--demo", action="store_true", help="Run built-in PHP2Shell exposure, php.ini & composer.json demo")
    parser.add_argument("-o", "--output", help="Export assessment report to a .json or .csv file")
    args = parser.parse_args()

    print(BANNER)

    if args.write_hardened_ini and not (args.demo or args.target or args.input_list or args.php_ini or args.composer):
        ini_out = Path(args.write_hardened_ini)
        ini_out.write_text(HARDENED_INI_TEMPLATE, encoding="utf-8")
        print(f"[+] Wrote hardened drop-in configuration to {ini_out}")
        return

    if args.input_list:
        list_path = Path(args.input_list)
        if not list_path.is_file():
            print(f"[!] Error: Target list file not found: {args.input_list}")
            sys.exit(1)
        batch_results = run_batch_scan(list_path)
        if args.output:
            export_report(batch_results, Path(args.output))
        return

    if args.demo:
        ini_map = parse_php_ini(DEMO_PHP_INI)
        report = evaluate_exposure(
            target_label="https://portal.example.com + php.ini + composer.json (Demo)",
            headers=DEMO_HEADERS,
            ini_directives=ini_map,
            composer_data=DEMO_COMPOSER_JSON,
        )
    elif args.target or args.php_ini or args.dockerfile or args.composer:
        headers = {}
        ini_map = {}
        df_text = ""
        comp_data = None
        labels = []

        if args.target:
            try:
                headers = fetch_passive_headers(args.target)
                labels.append(args.target)
            except Exception as exc:
                print(f"[!] Could not fetch HTTP headers from {args.target}: {exc}")
                sys.exit(1)

        if args.php_ini:
            p_ini = Path(args.php_ini)
            if not p_ini.is_file():
                print(f"[!] Error: php.ini file not found: {args.php_ini}")
                sys.exit(1)
            ini_map = parse_php_ini(p_ini.read_text(encoding="utf-8", errors="ignore"))
            labels.append(p_ini.name)

        if args.dockerfile:
            p_df = Path(args.dockerfile)
            if not p_df.is_file():
                print(f"[!] Error: Dockerfile not found: {args.dockerfile}")
                sys.exit(1)
            df_text = p_df.read_text(encoding="utf-8", errors="ignore")
            labels.append(p_df.name)

        if args.composer:
            p_comp = Path(args.composer)
            if not p_comp.is_file():
                print(f"[!] Error: composer.json not found: {args.composer}")
                sys.exit(1)
            comp_data = json.loads(p_comp.read_text(encoding="utf-8", errors="ignore"))
            labels.append(p_comp.name)

        report = evaluate_exposure(" + ".join(labels), headers, ini_map, df_text, comp_data)
    else:
        parser.print_help()
        print("\n💡 Tip: Run with --demo to test against a simulated unpatched Apache mod_php target!")
        sys.exit(0)

    print_report(report)

    if args.write_hardened_ini:
        ini_out = Path(args.write_hardened_ini)
        ini_out.write_text(HARDENED_INI_TEMPLATE, encoding="utf-8")
        print(f"[+] Wrote hardened drop-in configuration to {ini_out}")

    if args.output:
        export_report(report, Path(args.output))


if __name__ == "__main__":
    main()
